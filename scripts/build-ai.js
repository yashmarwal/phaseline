#!/usr/bin/env node
// Builds what Phase AI reads:
//   content/ai/answers.json  -> public/ai-answers.json   (stored answers, buttons, starter questions; used in the browser)
//   content/ai/knowledge.md  -> api/_knowledge.js        (the facts the AI may use; used only on the server)
// {{email}}, {{whatsapp}} and {{hours}} come from site.config.json. {{name}} is filled in by the chat.
// Run with: node scripts/build-ai.js   (also runs as part of `npm run build`)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'site.config.json'), 'utf8'));
const answers = JSON.parse(fs.readFileSync(path.join(root, 'content/ai/answers.json'), 'utf8'));
const knowledge = fs.readFileSync(path.join(root, 'content/ai/knowledge.md'), 'utf8');

const fill = (s) => s
  .replace(/\{\{email\}\}/g, config.contactEmail)
  .replace(/\{\{whatsapp\}\}/g, config.whatsappNumber)
  .replace(/\{\{hours\}\}/g, config.hours);

// check the pieces fit together, so a typo in a file fails the build instead of the chat
const problems = [];
const ids = new Set(answers.entries.map((e) => e.id));
const checkActions = (list, where) => (list || []).forEach((a) => { if (!answers.actions[a]) problems.push(`${where}: unknown button "${a}"`); });
answers.entries.forEach((e) => {
  checkActions(e.actions, `entry ${e.id}`);
  if (e.choices && !answers.choices[e.choices]) problems.push(`entry ${e.id}: unknown choices "${e.choices}"`);
  if (!e.choiceOnly && !(e.rules || []).length) problems.push(`entry ${e.id}: no rules`);
  if (!e.answer || e.answer.split(/\s+/).length > 45) problems.push(`entry ${e.id}: answer is missing or longer than 45 words`);
});
Object.entries(answers.starters).forEach(([page, list]) => list.forEach((s) => { if (!ids.has(s.entry)) problems.push(`starters.${page}: unknown entry "${s.entry}"`); }));
Object.entries(answers.choices).forEach(([k, list]) => list.forEach((s) => { if (!ids.has(s.entry)) problems.push(`choices.${k}: unknown entry "${s.entry}"`); }));
['fallback', 'limit', 'busy', 'formDone'].forEach((k) => checkActions(answers[k].actions, k));
if (problems.length) { console.error('Phase AI content problems:\n - ' + problems.join('\n - ')); process.exit(1); }

const out = JSON.parse(fill(JSON.stringify(answers)));
out.contact = { email: config.contactEmail, whatsappNumber: config.whatsappNumber, whatsappLink: config.whatsappLink, hours: config.hours };
fs.writeFileSync(path.join(root, 'public/ai-answers.json'), JSON.stringify(out));

fs.writeFileSync(path.join(root, 'api/_knowledge.js'),
  `// Generated by scripts/build-ai.js from content/ai/knowledge.md. Edit that file, not this one.\n` +
  `module.exports = {\n  KNOWLEDGE: ${JSON.stringify(fill(knowledge).trim())},\n  ACTION_IDS: ${JSON.stringify(Object.keys(answers.actions))},\n};\n`);

const words = fill(knowledge).split(/\s+/).length;
console.log(`built public/ai-answers.json (${answers.entries.length} stored answers) and api/_knowledge.js (${words} words of knowledge)`);
